ORDER = list(GLYPHS)


def rows(ch: str) -> list[int]:
    """Eight row bytes; the 5x7 glyph sits at columns 1-5, rows 0-6."""
    g = GLYPHS[ch]
    out = []
    for r in range(8):
        s = g[r] if r < len(g) else ""
        v = 0
        for i, c in enumerate(s.ljust(5)[:5]):
            if c == "#":
                v |= 0x80 >> (i + 1)
        out.append(v)
    return out


def index(ch: str) -> int:
    return ORDER.index(ch)
