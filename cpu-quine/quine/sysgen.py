"""Generate the FPGA top level's helper logic.

build/crc96.v: the observer's CRC-32 update over a 96-bit word as a flat
GF(2) matrix (one reduction XOR per output bit), so synthesis builds shallow
balanced XOR trees instead of a 96-step chain.  The update equals the
bit-serial CRC-32 (reflected, polynomial 0xEDB88320), least significant bit
first, used by csrc/check_system.cpp.
"""

from __future__ import annotations

import sys
from pathlib import Path

POLY = 0xEDB88320


def serial(c: int, v: int, nbits: int = 96) -> int:
    for i in range(nbits):
        c = (c >> 1) ^ (POLY if (c ^ (v >> i)) & 1 else 0)
    return c


def generate() -> str:
    # the update is linear: y = A c xor B v; find the columns from unit vectors
    terms = [[] for _ in range(32)]
    for j in range(32):
        y = serial(1 << j, 0)
        for i in range(32):
            if (y >> i) & 1:
                terms[i].append(f"c[{j}]")
    for j in range(96):
        y = serial(0, 1 << j)
        for i in range(32):
            if (y >> i) & 1:
                terms[i].append(f"v[{j}]")
    o = ["// GENERATED by quine/sysgen.py -- CRC-32 update over 96 bits, LSB first", "`default_nettype none"]
    o.append("module crc96(input wire [31:0] c, input wire [95:0] v, output wire [31:0] y);")
    for i in range(32):
        o.append(f"    assign y[{i}] = ^{{{', '.join(terms[i])}}};")
    o += ["endmodule", "`default_nettype wire"]
    # self-check against the serial definition
    import random

    rnd = random.Random(1)
    for _ in range(200):
        c, v = rnd.getrandbits(32), rnd.getrandbits(96)
        y = 0
        for i in range(32):
            bit = 0
            for t in terms[i]:
                k = int(t[2:-1])
                bit ^= ((c if t[0] == "c" else v) >> k) & 1
            y |= bit << i
        assert y == serial(c, v)
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(generate())
