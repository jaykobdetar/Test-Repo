"""Generate the Verilog RTL of the core from arch.py.

The control unit is emitted as a table: one case entry per (MU, IR[15:8])
pair, taken straight from arch.CONTROL.  The datapath is a direct
transcription of arch.step().
"""

from __future__ import annotations

import sys
from pathlib import Path

from . import arch


def field_layout():
    layout, pos = [], 0
    for name, vals in arch.FIELDS.items():
        w = max(1, (len(vals) - 1).bit_length())
        layout.append((name, pos, w, vals))
        pos += w
    return layout, pos


def encode_ctrl(c: dict) -> int:
    layout, _ = field_layout()
    v = 0
    for name, pos, _w, vals in layout:
        v |= vals.index(c[name]) << pos
    return v


def const(name: str, value) -> str:
    return f"C_{name.upper()}_{str(value).upper()}"


def generate() -> str:
    layout, width = field_layout()
    o = []
    w = o.append
    w("// GENERATED by quine/rtlgen.py from quine/arch.py -- do not edit.")
    w("// CPU-Quine core: single clock, rising-edge flip-flops with async active-low")
    w("// reset, no latches, no tristates.  Every flip-flop resets to zero.")
    w("`default_nettype none")
    w("module core (")
    w("    input  wire        clk,")
    w("    input  wire        rst_n,")
    w("    input  wire [15:0] rdata,  // memory data, registered by the memory")
    w("    output reg  [15:0] addr,   // address for the read/write of this cycle")
    w("    output wire        space,  // 0 = ROM, 1 = RAM")
    w("    output wire        we,     // write enable (RAM space only)")
    w("    output reg  [15:0] wdata,")
    order = ", ".join(n for n, _ in reversed(arch.REGISTERS))
    total = sum(wd for _, wd in arch.REGISTERS)
    w(f"    output wire [{total - 1}:0] state  // observation only: {{{order}}}")
    w(");")
    for name, wd in arch.REGISTERS:
        w(f"    reg [{wd - 1}:0] {name};")
    w("    wire fz = F[0], fn = F[1], fc = F[2];")
    w(f"    assign state = {{{', '.join(n for n, _ in reversed(arch.REGISTERS))}}};")
    w("")
    w(f"    // ---- control word ({width} bits) ----")
    for name, pos, fw, vals in layout:
        for i, v in enumerate(vals):
            w(f"    localparam [{fw - 1}:0] {const(name, v)} = {fw}'d{i};")
    w(f"    reg [{width - 1}:0] ctl;")
    for name, pos, fw, _ in layout:
        w(f"    wire [{fw - 1}:0] c_{name} = ctl[{pos + fw - 1}:{pos}];")
    w("")
    w("    always @* begin")
    w("        casez ({MU, IR[15:8]})")
    w(f"            10'b00_????????: ctl = {width}'h{encode_ctrl(arch.U_FETCH):X};  // fetch")
    w(f"            10'b01_????????: ctl = {width}'h{encode_ctrl(arch.U_DECODE):X};  // decode")
    for mu in (2, 3):
        for hb in range(256):
            c = arch.CONTROL[hb, mu]
            info = arch.decode(hb)
            desc = info.name + (f" {info.mode} {'RAM' if info.space else 'ROM'}" if info.kind == "mem" else "")
            w(f"            10'b{mu:02b}_{hb:08b}: ctl = {width}'h{encode_ctrl(c):X};  // {desc} u{mu}")
    w(f"            default: ctl = {width}'h{encode_ctrl(arch.NOP):X};")
    w("        endcase")
    w("    end")
    w("")
    w("    // ---- operand selection ----")
    w("    reg [15:0] L, R;")
    w("    always @* begin")
    w("        case (c_l)")
    w(f"            {const('l', 'A')}: L = A;")
    w(f"            {const('l', 'X')}: L = X;")
    w(f"            {const('l', 'Y')}: L = Y;")
    w(f"            {const('l', 'PC')}: L = {{1'b0, PC}};")
    w(f"            {const('l', 'SP')}: L = {{8'd0, SP}};")
    w("            default: L = 16'd0;")
    w("        endcase")
    w("        case (c_r)")
    w(f"            {const('r', 'ONE')}: R = 16'd1;")
    w(f"            {const('r', 'OFF')}: R = {{{{6{{IR[9]}}}}, IR[9:0]}};")
    w("            default: R = rdata;")
    w("        endcase")
    w("    end")
    w("")
    w("    // ---- ALU ----")
    w(f"    wire sub = (c_alu == {const('alu', 'SUB')}) || (c_alu == {const('alu', 'SBC')});")
    w(f"    wire cin = (c_alu == {const('alu', 'SUB')}) ? 1'b1 :")
    w(f"               ((c_alu == {const('alu', 'ADC')}) || (c_alu == {const('alu', 'SBC')})) ? fc : 1'b0;")
    w("    wire [16:0] sum = {1'b0, L} + {1'b0, sub ? ~R : R} + {16'd0, cin};")
    w("    reg [15:0] res;")
    w("    reg cout;")
    w("    always @* begin")
    w("        cout = 1'b0;")
    w("        case (c_alu)")
    for op in ("ADD", "ADC", "SUB", "SBC"):
        w(f"            {const('alu', op)}: {{cout, res}} = sum;")
    w(f"            {const('alu', 'AND')}: res = L & R;")
    w(f"            {const('alu', 'OR')}: res = L | R;")
    w(f"            {const('alu', 'XOR')}: res = L ^ R;")
    w(f"            {const('alu', 'SHL')}: begin res = {{L[14:0], 1'b0}}; cout = L[15]; end")
    w(f"            {const('alu', 'SHR')}: begin res = {{1'b0, L[15:1]}}; cout = L[0]; end")
    w(f"            {const('alu', 'ROL')}: begin res = {{L[14:0], fc}}; cout = L[15]; end")
    w(f"            {const('alu', 'ROR')}: begin res = {{fc, L[15:1]}}; cout = L[0]; end")
    w(f"            {const('alu', 'SWAB')}: res = {{L[7:0], L[15:8]}};")
    w("            default: res = L;  // PASS")
    w("        endcase")
    w("    end")
    w("")
    w("    // ---- branch condition, selected by IR[12:10] ----")
    w("    reg cond;")
    w("    always @* begin")
    w("        case (IR[12:10])")
    w("            3'd0: cond = 1'b1;")
    w("            3'd1: cond = fz;")
    w("            3'd2: cond = ~fz;")
    w("            3'd3: cond = fc;")
    w("            3'd4: cond = ~fc;")
    w("            3'd5: cond = fn;")
    w("            3'd6: cond = ~fn;")
    w("            default: cond = |X;")
    w("        endcase")
    w("    end")
    w("")
    w("    // ---- memory bus ----")
    w("    wire [7:0] sp_inc = SP + 8'd1;")
    w("    wire [7:0] sp_dec = SP - 8'd1;")
    w("    wire [14:0] pc_inc = PC + 15'd1;")
    w(f"    wire [7:0] stack_page = 8'h{arch.STACK_BASE >> 8:02X};")
    w("    always @* begin")
    w("        case (c_adr)")
    w(f"            {const('adr', 'ALU')}: addr = res;")
    w(f"            {const('adr', 'STK')}: addr = {{stack_page, SP}};")
    w(f"            {const('adr', 'STK1')}: addr = {{stack_page, sp_inc}};")
    w(f"            {const('adr', 'BR')}: addr = cond ? res : {{1'b0, PC}};")
    w("            default: addr = {1'b0, PC};")
    w("        endcase")
    w("        case (c_wd)")
    w(f"            {const('wd', 'X')}: wdata = X;")
    w(f"            {const('wd', 'Y')}: wdata = Y;")
    w(f"            {const('wd', 'PC')}: wdata = {{1'b0, PC}};")
    w("            default: wdata = A;")
    w("        endcase")
    w("    end")
    w("    assign space = c_space[0];")
    w("    assign we = c_we[0];")
    ops = [arch.OP5.index(n) for n in arch.OPERAND_OP5]
    w("    wire has_operand = rdata[15] | " + " | ".join(f"(rdata[14:10] == 5'd{v})" for v in ops) + ";")
    w("")
    w("    // ---- state update ----")
    w("    always @(posedge clk or negedge rst_n) begin")
    w("        if (!rst_n) begin")
    for name, wd in arch.REGISTERS:
        w(f"            {name} <= {wd}'d0;")
    w("        end else begin")
    w("            case (c_dst)")
    w(f"                {const('dst', 'A')}: A <= res;")
    w(f"                {const('dst', 'X')}: X <= res;")
    w(f"                {const('dst', 'Y')}: Y <= res;")
    w(f"                {const('dst', 'SP')}: SP <= res[7:0];")
    w("                default: ;")
    w("            endcase")
    w("            if (c_zn[0]) begin")
    w("                F[0] <= (res == 16'd0);")
    w("                F[1] <= res[15];")
    w("            end")
    w("            case (c_cf)")
    w(f"                {const('cf', 'ALU')}: F[2] <= cout;")
    w(f"                {const('cf', 'CLR')}: F[2] <= 1'b0;")
    w(f"                {const('cf', 'SET')}: F[2] <= 1'b1;")
    w("                default: ;")
    w("            endcase")
    w("            case (c_sp)")
    w(f"                {const('sp', 'DEC')}: SP <= sp_dec;")
    w(f"                {const('sp', 'INC')}: SP <= sp_inc;")
    w("                default: ;")
    w("            endcase")
    w("            case (c_pc)")
    w(f"                {const('pc', 'INC')}: PC <= pc_inc;")
    w(f"                {const('pc', 'INC_OP')}: if (has_operand) PC <= pc_inc;")
    w(f"                {const('pc', 'ALU')}: PC <= res[14:0];")
    w(f"                {const('pc', 'BR')}: if (cond) PC <= res[14:0];")
    w("                default: ;")
    w("            endcase")
    w("            if (c_ir[0]) IR <= rdata;")
    w("            MU <= c_mu;")
    w("        end")
    w("    end")
    w("endmodule")
    w("`default_nettype wire")
    return "\n".join(o) + "\n"


def main(argv):
    out = Path(argv[1])
    out.write_text(generate())


if __name__ == "__main__":
    main(sys.argv)
