def inset_asm() -> str:
    o = ["; GENERATED by quine/engine_gen.py -- the picture-in-picture",
         "; For each of 120 output rows: guest rows 2r and 2r+1 (40 consecutive guest",
         "; words) are read through the page table; each 2x2 block is OR-ed to one pixel."]  # fmt: skip
    o += [
        "draw_inset:",
        "    LDA #FB",
        "    STA iga",
        f"    LDA #FB+{INSET_Y0 * FB_STRIDE}",
        "    STA iout",
        "    LDA #120",
        "    STA icnt",
        ".row:",
        "    LDA iga",
        "    AND #$FF",
        "    CMP #217",
        "    BCS .slow",
        "    LDA iga",
        "    STA ga",
        "    SWAB",
        "    AND #$FF",
        "    TAX",
        "    LDA ga",
        "    ADD PTAB,X",
        "    STA isrc",
        "    JMP .body",
        ".slow:",  # copy the 40 words one by one through the page table
        "    LDA #0",
        "    STA t0",
        ".cp:",
        "    LDA iga",
        "    ADD t0",
        "    GREAD",
        "    LDY t0",
        "    STA IBUF,Y",
        "    INY",
        "    STY t0",
        "    CPY #40",
        "    BNE .cp",
        "    LDA #IBUF",
        "    STA isrc",
        ".body:",
        "    LDY iout",
    ]
    for j in range(10):
        a, b = 2 * j, 2 * j + 1
        o += [
            "    LDX isrc",
            f"    LDA {a},X",
            f"    OR {a + 20},X",
            "    STA ia",
            f"    LDA {b},X",
            f"    OR {b + 20},X",
            "    STA ib",
            "    OR ia",
            f"    BEQ .z{j}",
            "    LDA ia",
            "    SWAB",
            "    AND #$FF",
            "    TAX",
            "    LDA rom CT12,X",
            "    STA io",
            "    LDA ia",
            "    AND #$FF",
            "    TAX",
            "    LDA rom CT8,X",
            "    OR io",
            "    STA io",
            "    LDA ib",
            "    SWAB",
            "    AND #$FF",
            "    TAX",
            "    LDA rom CT4,X",
            "    OR io",
            "    STA io",
            "    LDA ib",
            "    AND #$FF",
            "    TAX",
            "    LDA rom CT0,X",
            "    OR io",
            f".z{j}:",
            f"    STA {j},Y",
        ]
    o += [
        "    LDA iga",
        "    ADD #40",
        "    STA iga",
        "    LDA iout",
        "    ADD #20",
        "    STA iout",
        "    LDA icnt",
        "    SUB #1",
        "    STA icnt",
        "    BEQ .done",
        "    JMP .row",
        ".done:",
        "    RTS",
    ]

    def ct(v):
        return sum(1 << (3 - i) for i in range(4) if (v >> (7 - 2 * i)) & 3)

    for name, sh in (("CT12", 12), ("CT8", 8), ("CT4", 4), ("CT0", 0)):
        vals = [ct(v) << sh for v in range(256)]
        o.append(f"{name}:")
        o += ["    .word " + ", ".join(f"${x:04X}" for x in vals[i : i + 16]) for i in range(0, 256, 16)]
    return "\n".join(o) + "\n"


