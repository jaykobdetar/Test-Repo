# Transistor expansion and die map
# --------------------------------------------------------------------------


def single_stage(name: str, pats: dict) -> bool:
    """True if N row == input bits and P row == their complement, in input order."""
    p = pats[name]
    n = len(p["inputs"])
    types = p["types"]
    if types.count("P") != n or types.count("N") != n:
        return False
    for k, st in enumerate(p["states"]):
        ps = [s for s, t in zip(st, types) if t == "P"]
        ns = [s for s, t in zip(st, types) if t == "N"]
        if ns != [(k >> i) & 1 for i in range(n)] or ps != [1 - ((k >> i) & 1) for i in range(n)]:
            return False
    return True


def row_bits(states, types, kind, shift_left_px):
    """Pixel word for one row of a cell: transistor i of that kind at pixel (left + i)."""
    w = 0
    i = 0
    for s, t in zip(states, types):
        if t == kind:
            if s:
                w |= 1 << (15 - shift_left_px - i)
            i += 1
    return w


def place(nl, pats):
    """Die-map placement: comb cells in levelized order in 4-px slots; one
    register per row of 16-px flip-flops at the bottom."""
    slots = []  # (gate, word_index_in_fb, slot_q)
    word = 0
    row = 0
    q = 0
    for g in nl.gates:
        w_slots = 1 if max(pats[g.type]["types"].count("P"), pats[g.type]["types"].count("N")) <= 3 else 2
        if q + w_slots > 4:
            q, word = 0, word + 1
        if word >= FB_STRIDE:
            word, row = 0, row + 1
        slots.append((g, row, word, q, w_slots))
        q += w_slots
        if q == 4:
            q, word = 0, word + 1
    comb_rows = row + (1 if (word or q) else 0)
    reg_y0 = DIE_Y0 + comb_rows * DIE_ROW_H + 4
    reg_rows = [["A"], ["X"], ["Y"], ["PC"], ["IR"], ["SP", "MU", "F"]]
    dffs = []  # (dff gate, y, word)
    byreg = {}
    for d in nl.dffs:
        r, b = nl.ff_reg[d.out]
        byreg.setdefault(r, {})[b] = d
    for i, regs in enumerate(reg_rows):
        y = reg_y0 + i * DIE_ROW_H
        col = 0
        for r in regs:
            wd = dict(arch.REGISTERS)[r]
            for b in range(wd - 1, -1, -1):  # MSB on the left
                dffs.append((byreg[r][b], y, col))
                col += 1
            col += 1
    end_y = reg_y0 + len(reg_rows) * DIE_ROW_H
    if end_y > INSET_Y0:
        raise ValueError(f"die map does not fit: needs {end_y} rows")
    return slots, dffs, comb_rows, end_y


def cells_asm(nl, sl, pats) -> tuple[str, dict]:
    idx = sl["index"]

    def nb(net):
        p = idx[net]
        return f"NB+{p >> 4}", f"${1 << (p & 15):04X}"

    o = ["; GENERATED by quine/engine_gen.py -- transistor expansion, die map, latch, hash"]
    slots, dffs, comb_rows, die_end = place(nl, pats)
    types_used = sorted({g.type for g in nl.gates})
    # ---- expansion entry ----
    full = {sl["words"][f"Q_{r}"] for r in REG_NAMES} | {sl["words"]["RDATA"], sl["words"]["MISC"]}
    o.append("expand:  ; guest full state (gA..gF, gRD) -> net bitset + die map")
    o.append("    LDA #0")
    for w in range(sl["nwords"]):
        if w not in full:
            o.append(f"    STA NB+{w}")
    o.append("    STA accN")
    o.append("    STA accP")
    for r in REG_NAMES:
        o += [f"    LDA {('g' + r)}", f"    STA W_Q_{r}"]
    o += ["    LDA gRD", "    STA W_RDATA", "    LDA #MISC_INIT", "    STA W_MISC"]
    o += ["    LDX #CELLS", "    JMPX 0"]
    # ---- per-type evaluation handlers ----
    o.append("; cell record: handler, (word, mask) per input, out word, out mask, slot offset")
    for t in types_used:
        c = CELLS[t]
        n = len(c.inputs)
        ss = single_stage(t, pats)
        o.append(f"ce_{t}:  ; {'single stage' if ss else 'general'}")
        recl = 4 + 2 * n
        if not ss:
            recl += 0

        def leaf(k):
            L = [f".k{k}:"]
            out = CELLS[t].fn({p: (k >> i) & 1 for i, p in enumerate(c.inputs)})
            if out:
                L += [f"    LDY rom {1 + 2 * n},X", "    LDA 0,Y", f"    OR rom {2 + 2 * n},X", "    STA 0,Y"]
            if ss:
                if k:
                    L += [f"    LDY rom {3 + 2 * n},X", f"    LDA rom SHTAB+{k},Y", "    OR accN", "    STA accN"]
            else:
                L += [f"    LDY rom {3 + 2 * n},X", f"    LDA rom PN_{t}+{k},Y", "    OR accN", "    STA accN"]
                L += [f"    LDA rom PP_{t}+{k},Y", "    OR accP", "    STA accP"]
            L += ["    TXA", f"    ADD #{recl}", "    TAX", "    JMPX 0"]
            return L

        def node(depth, k):
            if depth == n:
                return leaf(k)
            lab = f".n{depth}_{k | (1 << depth)}"
            L = [f"    LDY rom {1 + 2 * depth},X", "    LDA 0,Y", f"    AND rom {2 + 2 * depth},X", f"    BNE {lab}"]
            L += node(depth + 1, k)
            L += [f"{lab}:"] + node(depth + 1, k | (1 << depth))
            return L

        o += node(0, 0)
    o += [
        "ce_flush:  ; record: handler, fb address (P row), mask of single-stage pixels",
        "    LDY rom 1,X",
        "    LDA accN",
        "    STA 20,Y",
        "    AND rom 2,X",
        "    XOR rom 2,X",
        "    OR accP",
        "    STA 0,Y",
        "    LDA #0",
        "    STA accN",
        "    STA accP",
        "    TXA",
        "    ADD #3",
        "    TAX",
        "    JMPX 0",
        "ce_end:",
        "    RTS",
    ]
    # ---- shift tables ----
    o.append("SHTAB:  ; single-stage N-row pixels: [16*slot + k]")
    sh = []
    for q in range(4):
        for k in range(16):
            sh.append(sum(((k >> i) & 1) << (15 - 4 * q - i) for i in range(3)))
    for i in range(0, 64, 16):
        o.append("    .word " + ", ".join(f"${x:04X}" for x in sh[i : i + 16]))
    for t in types_used:
        if single_stage(t, pats):
            continue
        p = pats[t]
        pn, pp = [], []
        for q in range(4):
            for k in range(16):
                st = p["states"][k] if k < len(p["states"]) else [0] * len(p["types"])
                pn.append(row_bits(st, p["types"], "N", 4 * q) if q <= 2 else 0)
                pp.append(row_bits(st, p["types"], "P", 4 * q) if q <= 2 else 0)
        o.append(f"PN_{t}:")
        o += ["    .word " + ", ".join(f"${x:04X}" for x in pn[i : i + 16]) for i in range(0, 64, 16)]
        o.append(f"PP_{t}:")
        o += ["    .word " + ", ".join(f"${x:04X}" for x in pp[i : i + 16]) for i in range(0, 64, 16)]
    # ---- cell records, with flush records after each completed word ----
    o.append("CELLS:")
    nrec = 0
    words = 0
    cur = None
    mask = 0
    for i, (g, row, word, q, ws) in enumerate(slots):
        key = (row, word)
        if cur is not None and key != cur:
            o.append(f"    .word ce_flush, {fb_addr(*cur)}, ${mask:04X}")
            words += 3
            mask = 0
        cur = key
        c = CELLS[g.type]
        ins = []
        for p_ in c.inputs:
            ins += list(nb(g.ins[p_]))
        ow, om = nb(g.out)
        o.append(f"    .word ce_{g.type}, {', '.join(ins)}, {ow}, {om}, {16 * q}")
        words += 4 + 2 * len(c.inputs)
        nrec += 1
        if single_stage(g.type, pats):
            n = len(c.inputs)
            for j in range(n):
                mask |= 1 << (15 - 4 * q - j)
    if cur is not None:
        o.append(f"    .word ce_flush, {fb_addr(*cur)}, ${mask:04X}")
        words += 3
    o.append("    .word ce_end")
    words += 1
    # ---- flip-flops ----
    dp = pats["DFFR"]
    o.append("draw_dffs:  ; record: Q word, Q mask, D word, D mask, fb address")
    o += [
        "    LDX #DFFS",
        ".lp:",
        "    LDY rom 0,X",
        "    BEQ .done",
        "    LDA 0,Y",
        "    AND rom 1,X",
        "    STA t0",
        "    LDY rom 2,X",
        "    LDA 0,Y",
        "    AND rom 3,X",
        "    BEQ .d0",
        "    LDA t0",
        "    BEQ .k1",
    ]
    for k, lab in ((3, None), (1, ".k1"), (2, ".k2"), (0, ".k0")):
        st = dp["states"][k]  # CK = 0
        P = row_bits(st, dp["types"], "P", 0)
        N = row_bits(st, dp["types"], "N", 0)
        if lab:
            o.append(f"{lab}:")
        o += [f"    LDA #${P:04X}", "    STA t1", f"    LDA #${N:04X}", "    JMP .draw"]
        if k == 1:
            o += [".d0:", "    LDA t0", "    BEQ .k0", "    JMP .k2"]
    o += [
        ".draw:",
        "    LDY rom 4,X",
        "    STA 20,Y",
        "    LDA t1",
        "    STA 0,Y",
        "    TXA",
        "    ADD #5",
        "    TAX",
        "    JMP .lp",
        ".done:",
        "    RTS",
    ]
    o.append("DFFS:")
    for d, y, col in dffs:
        qw, qm = nb(d.out)
        dw, dm = nb(d.ins["D"])
        o.append(f"    .word {qw}, {qm}, {dw}, {dm}, FB+{y * FB_STRIDE + col}")
    o.append("    .word 0")
    words += 5 * len(dffs) + 1
    # ---- latch: next state from the D words ----
    o.append("latch_regs:  ; guest registers <= D nets (the rising edge)")
    for r in REG_NAMES:
        wd = dict(arch.REGISTERS)[r]
        if len(sl["d_aligned"][r]) == wd:
            o += [f"    LDA W_D_{r}", f"    STA g{r}"]
        else:
            o += ["    LDA #0", f"    STA g{r}"]
            for d in nl.dffs:
                rr, b = nl.ff_reg[d.out]
                if rr != r:
                    continue
                w_, m_ = nb(d.ins["D"])
                o += [f"    LDA {w_}", f"    AND #{m_}", f"    BEQ .z_{r}_{b}", f"    LDA g{r}", f"    OR #${1 << b:04X}",
                      f"    STA g{r}", f".z_{r}_{b}:"]  # fmt: skip
    o.append("    RTS")
    for port in ("addr", "wdata"):
        if len(sl["bus_aligned"][port]) != 16:
            raise ValueError(f"bus {port} not word aligned; latch code would need a gather")
    # ---- frame hash ----
    o.append("emit_hash:  ; debug port <- guest cycle (3 words) and the bitset hash")
    o += [
        "    LDA gCYC0",
        "    STA IO_DEBUG",
        "    LDA gCYC1",
        "    STA IO_DEBUG",
        "    LDA gCYC2",
        "    STA IO_DEBUG",
        "    LDA #0",
    ]
    for w in range(sl["nwords"]):
        o += ["    SHL", "    ADC #0", f"    XOR NB+{w}"]
    o += ["    STA hash", "    STA IO_DEBUG", "    RTS"]
    info = {"cell_records": nrec, "cell_table_words": words, "comb_rows": comb_rows, "die_end_row": die_end}
    return "\n".join(o) + "\n", info


def fb_addr(row, word):
    return f"FB+{(DIE_Y0 + row * DIE_ROW_H) * FB_STRIDE + word}"


