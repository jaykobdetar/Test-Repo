def c_header(sl, symbols: dict, info: dict) -> str:
    o = [
        "/* GENERATED by quine/engine_gen.py -- engine layout for the C tools */",
        "#ifndef QENGINE_H",
        "#define QENGINE_H",
    ]
    for v, a in VAR_ADDR.items():
        o.append(f"#define QE_{v} {a:#x}")
    o.append(f"#define QE_NB {NB_BASE:#x}")
    o.append(f"#define QE_NB_WORDS {sl['nwords']}")
    o.append(f"#define QE_PTAB {PTAB:#x}")
    o.append(f"#define QE_FB {FB:#x}")
    o.append(f"#define QE_FB_WORDS {FB_WORDS}")
    o.append(f"#define QE_FIRST_GUEST_PAGE {FIRST_GUEST_PAGE}")
    o.append(f"#define QE_WORKING_PAGES {WORKING_PAGES}")
    o.append(f"#define QE_MISC_INIT {MISC_INIT}")
    for name, w in sl["words"].items():
        o.append(f"#define QE_W_{name} {w}")
    for name in ("show", "watch", "ff_carry", "expand", "boot"):
        o.append(f"#define QE_SYM_{name.upper()} {symbols[name]:#x}")
    syncs = sorted(v for k, v in symbols.items() if k.startswith("ffsync_"))
    o.append(f"#define QE_NSYNC {len(syncs)}")
    o.append("static const uint16_t qe_sync[QE_NSYNC] = {" + ",".join(str(s) for s in syncs) + "};")
    lat = sorted(v for k, v in symbols.items() if k.startswith("watch.latched"))
    o.append(f"#define QE_NLATCH {len(lat)}")
    o.append("static const uint16_t qe_latched[QE_NLATCH] = {" + ",".join(str(s) for s in lat) + "};")
    o.append("#endif")
    return "\n".join(o) + "\n"
