"""Generate the replay engine's derived assembly and its C description.

From arch.py, the netlist, the slot layout and the cell patterns this emits:

  gen_layout.s   RAM layout and net-state bitset symbols
  gen_stepper.s  the instruction stepper: one handler per opcode high byte,
                 the dispatch table and the branch-offset table
  gen_cells.s    the transistor expansion: per-type evaluation handlers, the
                 levelized cell records with their die-map placement, the
                 flip-flop drawing table, latch and hash code
  gen_text.s     font, hex and mnemonic tables, and the status panel code
  gen_inset.s    the half-scale picture of the guest's own screen
  qengine.h      the same layout for the C emulator and checks

Hand-written logic lives in engine/main.s.
"""

from __future__ import annotations

from . import arch, font
from .cells import CELLS

# --------------------------------------------------------------------------
# RAM layout (identical at every nesting level)
# --------------------------------------------------------------------------

REG_NAMES = [r for r, _ in arch.REGISTERS]
VARS = [
    # guest flip-flops in arch.REGISTERS order (the full state)
    "gA", "gX", "gY", "gSP", "gPC", "gIR", "gMU", "gF",
    # compact-state extras: lazy Z/N (gRES), carry, RDATA, 48-bit cycle count
    "gRES", "gC", "gRD", "gCYC0", "gCYC1", "gCYC2",
    # guest memory
    "nextp", "ga", "gv", "greset", "gtmp", "gtmp2",
    # scratch
    "t0", "t1", "t2", "t3", "t4", "t5",
    # show script and drawing
    "fcount", "frames_left", "wcount", "accN", "accP", "mode", "nrd",
    "iga", "iout", "icnt", "isrc", "ia", "ib", "io", "hash", "tdst",
    "tw0", "tw1", "tw2", "tw3", "tw4", "tw5", "tw6", "tw7",
]  # fmt: skip
VAR_ADDR = {v: i for i, v in enumerate(VARS)}
assert len(VARS) <= 0x40
NB_BASE = 0x40
IBUF = 0xD8  # 40-word copy buffer for inset rows that cross a page
PTAB = 0x100
STACK = 0x200
FB = 0x300
FB_ROWS, FB_STRIDE = 240, 20
FB_WORDS = FB_ROWS * FB_STRIDE
FB_END = FB + FB_WORDS
WORKING_PAGES = (FB_END + 255) // 256  # pages 0..21
FIRST_GUEST_PAGE = WORKING_PAGES
DIE_Y0 = 2  # first pixel row of the die map
DIE_ROW_H = 4  # P row, N row, two blank rows
DIE_SLOTS = 80  # 4-pixel slots per die row
TEXT_Y0, TEXT_X0W = 120, 10  # status panel: rows 120.., word columns 10..19
INSET_Y0 = 120

MISC_SPACE = 1 << 4
MISC_WE = 1 << 5
MISC_INIT = (1 << 1) | (1 << 3)  # CONST1 and rst_n high; clk low (drawn half-cycle)


def layout_asm(sl) -> str:
    o = ["; GENERATED by quine/engine_gen.py -- RAM layout and net-state bitset"]
    for v, a in VAR_ADDR.items():
        o.append(f"{v} = ${a:04X}")
    o.append(f"NB = ${NB_BASE:04X}")
    o.append(f"NB_WORDS = {sl['nwords']}")
    o.append("NB_END = NB + NB_WORDS")
    for name, w in sl["words"].items():
        o.append(f"W_{name} = NB + {w}")
    o.append(f"IBUF = ${IBUF:04X}")
    o.append(f"PTAB = ${PTAB:04X}")
    o.append(f"FB = ${FB:04X}")
    o.append(f"FB_END = ${FB_END:04X}")
    o.append(f"FIRST_GUEST_PAGE = {FIRST_GUEST_PAGE}")
    o.append(f"RAM_PAGES = {arch.RAM_PAGES}")
    o.append(f"IO_DEBUG = ${arch.IO_DEBUG:04X}")
    o.append(f"IO_RESET = ${arch.IO_RESET:04X}")
    o.append(f"MISC_SPACE = {MISC_SPACE}")
    o.append(f"MISC_WE = {MISC_WE}")
    o.append(f"MISC_INIT = {MISC_INIT}")
    o.append(f"DBNE_SELF = ${arch.encode_op5('DBNE', -1):04X}")
    o.append(f"OP_DBNE_HB = {arch.OP5.index('DBNE') << 2}")
    o.append('.assert NB_END <= IBUF, "net bitset overlaps the inset buffer"')
    o.append('.assert IBUF + 40 <= $100, "page 0 overflow"')
    return "\n".join(o) + "\n"


# --------------------------------------------------------------------------
# Instruction stepper
# --------------------------------------------------------------------------

PC_PLUS = {1: ["    TYA", "    ADD #1", "    AND #$7FFF", "    STA gPC"], 2: ["    TYA", "    ADD #2", "    AND #$7FFF", "    STA gPC"]}  # fmt: skip
SAVEC = ["    LDA #0", "    ROL", "    STA gC"]
LOADC = ["    LDA gC", "    SHR"]


def gread() -> list[str]:
    """A = guest RAM address -> A = word (8 instructions, clobbers X)."""
    return ["    GREAD"]


def store_tail() -> list[str]:
    """After a guest write: a write to the guest's reset address restarts the guest."""
    return ["    JSR gwrite", "    LDA greset", "    BEQ .wok", "    JMP guest_reset_ff", ".wok:"]


def mem_handler(hb: int) -> list[str]:
    info = arch.decode(hb)
    op, mode, space = info.name, info.mode, info.space
    n = arch.cycles(hb)
    L = []
    if op in arch.STORES:
        L += ["    LDA rom 1,Y"]
        if mode == "absx":
            L += ["    ADD gX"]
        elif mode == "absy":
            L += ["    ADD gY"]
        L += ["    STA ga", f"    LDA g{arch.REG_OF[op]}"]
        L += store_tail()
        L += PC_PLUS[2] + [f"    NEXT {n}"]
        return L
    L += ["    LDA rom 1,Y"]
    if mode != "imm":
        if mode == "absx":
            L += ["    ADD gX"]
        elif mode == "absy":
            L += ["    ADD gY"]
        if space == arch.SPACE_ROM:
            L += ["    TAX", "    LDA rom 0,X"]
        else:
            L += gread()
    reg = arch.REG_OF.get(op)
    if op in arch.LOADS:
        L += [f"    STA g{reg}", "    STA gRES"]
    elif op in ("ADD",):
        L += ["    ADD gA", "    STA gA", "    STA gRES"] + SAVEC
    elif op == "ADC":
        L += ["    STA t0"] + LOADC + ["    LDA t0", "    ADC gA", "    STA gA", "    STA gRES"] + SAVEC
    elif op == "SUB":
        L += ["    STA t0", "    LDA gA", "    SUB t0", "    STA gA", "    STA gRES"] + SAVEC
    elif op == "SBC":
        L += ["    STA t0"] + LOADC + ["    LDA gA", "    SBC t0", "    STA gA", "    STA gRES"] + SAVEC
    elif op in arch.LOGIC:
        L += [f"    {op} gA", "    STA gA", "    STA gRES"]
    elif op in arch.COMPARES:
        L += ["    STA t0", f"    LDA g{reg}", "    SUB t0", "    STA gRES"] + SAVEC
    L += PC_PLUS[2] + [f"    NEXT {n}"]
    return L


BRANCH_TEST = {
    "BRA": [],
    "BEQ": ["    LDA gRES", "    BNE .nt"],
    "BNE": ["    LDA gRES", "    BEQ .nt"],
    "BCS": ["    LDA gC", "    BEQ .nt"],
    "BCC": ["    LDA gC", "    BNE .nt"],
    "BMI": ["    LDA gRES", "    BPL .nt"],
    "BPL": ["    LDA gRES", "    BMI .nt"],
}
TAKEN = ["    LDA gIR", "    AND #$3FF", "    TAX", "    TYA", "    ADD rom SEXT1,X", "    AND #$7FFF", "    STA gPC"]


def branch_handler(hb: int) -> list[str]:
    name = arch.decode(hb).name
    n = arch.cycles(hb)
    if name == "DBNE":
        return [
            "    LDA gIR",
            "    AND #$3FF",
            "    CMP #$3FF",
            "    BEQ .idle",
            "    LDA gX",
            "    SUB #1",
            "    STA gX",
            "    BEQ .nt",
            *TAKEN,
            f"    NEXT {n}",
            ".nt:",
            *PC_PLUS[1],
            f"    NEXT {n}",
            ".idle:",
            "    JSR idle_skip",
            "    DISPATCH",
        ]
    L = list(BRANCH_TEST[name]) + TAKEN + [f"    NEXT {n}"]
    if BRANCH_TEST[name]:
        L += [".nt:"] + PC_PLUS[1] + [f"    NEXT {n}"]
    return L


IMPLIED = {
    "SHL": ["    LDA gA", "    SHL", "    STA gA", "    STA gRES", *SAVEC],
    "SHR": ["    LDA gA", "    SHR", "    STA gA", "    STA gRES", *SAVEC],
    "ROL": [*LOADC, "    LDA gA", "    ROL", "    STA gA", "    STA gRES", *SAVEC],
    "ROR": [*LOADC, "    LDA gA", "    ROR", "    STA gA", "    STA gRES", *SAVEC],
    "SWAB": ["    LDA gA", "    SWAB", "    STA gA", "    STA gRES"],
    "TAX": ["    LDA gA", "    STA gX", "    STA gRES"],
    "TAY": ["    LDA gA", "    STA gY", "    STA gRES"],
    "TXA": ["    LDA gX", "    STA gA", "    STA gRES"],
    "TYA": ["    LDA gY", "    STA gA", "    STA gRES"],
    "TSX": ["    LDA gSP", "    STA gX", "    STA gRES"],
    "TXS": ["    LDA gX", "    AND #$FF", "    STA gSP"],
    "INX": ["    LDA gX", "    ADD #1", "    STA gX", "    STA gRES"],
    "INY": ["    LDA gY", "    ADD #1", "    STA gY", "    STA gRES"],
    "DEX": ["    LDA gX", "    SUB #1", "    STA gX", "    STA gRES"],
    "DEY": ["    LDA gY", "    SUB #1", "    STA gY", "    STA gRES"],
    "CLC": ["    LDA #0", "    STA gC"],
    "SEC": ["    LDA #1", "    STA gC"],
    "ILL": [],
}


def other_handler(hb: int) -> list[str]:
    info = arch.decode(hb)
    name, n = info.name, arch.cycles(hb)
    if name in IMPLIED:
        return IMPLIED[name] + PC_PLUS[1] + [f"    NEXT {n}"]
    stk = ["    LDA gSP", "    OR #$200"]
    pop = ["    LDA gSP", "    ADD #1", "    AND #$FF", "    STA gSP", "    OR #$200", *gread()]
    dec_sp = ["    LDA gSP", "    SUB #1", "    AND #$FF", "    STA gSP"]
    if name == "PHA":
        return stk + ["    STA ga", "    LDA gA"] + store_tail() + dec_sp + PC_PLUS[1] + [f"    NEXT {n}"]
    if name == "PLA":
        return pop + ["    STA gA", "    STA gRES"] + PC_PLUS[1] + [f"    NEXT {n}"]
    if name == "RTS":
        return pop + ["    AND #$7FFF", "    STA gPC", f"    NEXT {n}"]
    if name == "JMP":
        return ["    LDA rom 1,Y", "    AND #$7FFF", "    STA gPC", f"    NEXT {n}"]
    if name == "JMPX":
        return [
            "    LDA rom 1,Y",
            "    ADD gX",
            "    TAX",
            "    LDA rom 0,X",
            "    AND #$7FFF",
            "    STA gPC",
            f"    NEXT {n}",
        ]
    if name == "JSR":
        return (
            stk
            + ["    STA ga", "    TYA", "    ADD #2", "    AND #$7FFF"]
            + store_tail()
            + dec_sp
            + ["    LDA rom 1,Y", "    AND #$7FFF", "    STA gPC", f"    NEXT {n}"]
        )
    raise ValueError(name)


def handler_name(hb: int) -> str:
    info = arch.decode(hb)
    if info.kind == "branch":
        return f"h_{info.name.lower()}"
    if info.kind == "illegal":
        return "h_ill"
    if info.kind == "mem":
        sp = "rom" if info.space == 0 else "ram"
        return f"h_{info.name.lower()}_{info.mode}_{sp}"
    return f"h_{info.name.lower()}"


def handler_body(hb: int) -> list[str]:
    info = arch.decode(hb)
    if info.kind == "mem":
        return mem_handler(hb)
    if info.kind == "branch":
        return branch_handler(hb)
    return other_handler(hb)


def stepper_asm() -> str:
    o = ["; GENERATED by quine/engine_gen.py from quine/arch.py -- the instruction stepper",
         "; Entry: Y = guest PC (set by DISPATCH).  Each handler ends in NEXT n, which adds",
         "; the instruction's cycle count from the microcode table and dispatches again.",
         "; Opcodes whose handlers would be identical share one (e.g. a store's space bit)."]  # fmt: skip
    by_body: dict[str, str] = {}
    label = {}
    for hb in range(256):
        body = handler_body(hb)
        key = "\n".join(body)
        if key not in by_body:
            name = handler_name(hb)
            by_body[key] = name
            info = arch.decode(hb)
            desc = f"{info.name} {info.mode or ''} {['ROM', 'RAM'][info.space] if info.space is not None else ''}"
            o.append(f"{name}:  ; {desc.strip()} -- {arch.cycles(hb)} cycles")
            o += body
        label[hb] = by_body[key]
    o.append("")
    o.append("DISPATCH_TABLE:")
    for hb in range(0, 256, 8):
        o.append("    .word " + ", ".join(label[h] for h in range(hb, hb + 8)))
    o.append("SEXT1:  ; sign-extended 10-bit branch offset + 1")
    vals = [((v - 0x400 if v & 0x200 else v) + 1) & 0xFFFF for v in range(1024)]
    for i in range(0, 1024, 16):
        o.append("    .word " + ", ".join(f"${x:04X}" for x in vals[i : i + 16]))
    return "\n".join(o) + "\n"


