STATIC_TEXT = [
    (0, 0, "GUEST CPU"),
    (2, 0, "CYCLE"),
    (4, 0, "PC"),
    (4, 10, "IR"),
    (5, 0, "A"),
    (5, 10, "X"),
    (6, 0, "Y"),
    (6, 10, "SP"),
    (7, 0, "ZNC"),
    (7, 10, "MU"),
    (11, 0, "PAGES"),
]


def text_asm() -> str:
    o = ["; GENERATED by quine/engine_gen.py -- status panel"]
    G = {ch: font.index(ch) * 8 for ch in font.ORDER}

    def fbw(line, col, y):
        return f"FB+{(TEXT_Y0 + 8 * line + y) * FB_STRIDE + TEXT_X0W + col // 2}"

    def at(line, col):
        assert col % 2 == 0, f"text pair at odd column {col}"
        return [f"    LDA #{fbw(line, col, 0)}", "    STA tdst", "    JSR tpair"]

    def pair_const(line, col, a, b):
        return [f"    LDX #{G[a]}", f"    LDY #{G[b]}"] + at(line, col)

    def hexdigit_to(var, nib, reg):
        sh = {0: [], 1: ["    SHR"] * 4, 2: ["    SWAB"], 3: ["    SWAB"] + ["    SHR"] * 4}[nib]
        return [
            f"    LDA {var}",
            *sh,
            "    AND #15",
            "    TAX",
            "    LDA rom HEXG,X",
            f"    {'STA t5' if reg == 'X' else 'TAY'}",
        ]

    def hex_pair(line, col, var, nib_hi):
        L = hexdigit_to(var, nib_hi, "X") + hexdigit_to(var, nib_hi - 1, "Y") + ["    LDX t5"]
        return L + at(line, col)

    def hex4(line, col, var):
        return hex_pair(line, col, var, 3) + hex_pair(line, col + 2, var, 1)

    def text_at(line, col, s):
        L = []
        if len(s) % 2:
            s += " "
        for i in range(0, len(s), 2):
            L += pair_const(line, col + i, s[i], s[i + 1])
        return L

    o.append("text_static:")
    for line, col, s in STATIC_TEXT:
        o += text_at(line, col, s)
    o.append("    RTS")
    o.append("text_dynamic:")
    o += hex4(3, 0, "gCYC2") + hex4(3, 6, "gCYC1") + hex4(3, 12, "gCYC0")
    o += hex4(4, 4, "gPC") + hex4(4, 14, "gIR")
    o += hex4(5, 4, "gA") + hex4(5, 14, "gX")
    o += hex4(6, 4, "gY") + hex_pair(6, 14, "gSP", 1)
    # flags Z N C as 0/1 digits, MU
    o += ["    LDA gF", "    AND #1", "    TAX", "    LDA rom HEXG,X", "    STA t5",
          "    LDA gF", "    SHR", "    AND #1", "    TAX", "    LDA rom HEXG,X", "    TAY", "    LDX t5"]  # fmt: skip
    o += at(7, 4)
    o += [
        "    LDA gF",
        "    SHR",
        "    SHR",
        "    AND #1",
        "    TAX",
        "    LDA rom HEXG,X",
        "    TAX",
        f"    LDY #{G[' ']}",
    ]
    o += at(7, 6)
    o += [f"    LDX #{G[' ']}", "    LDA gMU", "    AND #3", "    TAY", "    LDA rom HEXG,Y", "    TAY"]
    o += at(7, 14)
    # mnemonic: 4-character name and 6-character mode, via per-opcode indices
    o += [
        "    LDA gIR",
        "    SWAB",
        "    AND #$FF",
        "    TAX",
        "    LDA rom DISN,X",
        "    STA t4",
        "    LDA rom DISM,X",
        "    STA t3",
    ]
    for p in range(2):
        o += ["    LDY t4", f"    LDA rom NAMEG+{2 * p},Y", "    TAX", f"    LDA rom NAMEG+{2 * p + 1},Y", "    TAY"]
        o += at(9, 2 * p)
    for p in range(3):
        o += ["    LDY t3", f"    LDA rom MODEG+{2 * p},Y", "    TAX", f"    LDA rom MODEG+{2 * p + 1},Y", "    TAY"]
        o += at(9, 4 + 2 * p)
    # pages in use and mode
    o += ["    LDA nextp", "    SUB #FIRST_GUEST_PAGE", "    STA t3"]
    o += hex_pair(11, 6, "t3", 1)
    o += ["    LDA mode", "    BNE .fast"]
    o += text_at(13, 0, "WATCH ")
    o += ["    RTS", ".fast:"]
    o += text_at(13, 0, "REPLAY")
    o.append("    RTS")
    # one routine draws a pair of characters: X, Y = glyph offsets, tdst = top word
    o.append("tpair:")
    for y in range(8):
        o += [f"    LDA rom FONTH+{y},X", f"    OR rom FONTL+{y},Y", f"    STA tw{y}"]
    o.append("    LDX tdst")
    for y in range(8):
        o += [f"    LDA tw{y}", f"    STA {y * FB_STRIDE},X"]
    o.append("    RTS")
    # tables
    o.append("HEXG:")
    o.append("    .word " + ", ".join(str(G[c]) for c in "0123456789ABCDEF"))
    fh, fl = [], []
    for ch in font.ORDER:
        r = font.rows(ch)
        fh += [x << 8 for x in r]
        fl += r
    o.append("FONTH:")
    o += ["    .word " + ", ".join(f"${x:04X}" for x in fh[i : i + 16]) for i in range(0, len(fh), 16)]
    o.append("FONTL:")
    o += ["    .word " + ", ".join(f"${x:02X}" for x in fl[i : i + 16]) for i in range(0, len(fl), 16)]
    names, modes, dn, dm = [], [], [], []
    for hb in range(256):
        info = arch.decode(hb)
        nm = info.name.ljust(4)[:4]
        if info.kind == "mem":
            if info.mode == "imm":
                md = " #IMM "
            else:
                sp = "RAM" if info.space == 1 or info.name in arch.STORES else "ROM"
                md = " " + sp + {"abs": "  ", "absx": ",X", "absy": ",Y"}[info.mode]
        else:
            md = "      "
        if nm not in names:
            names.append(nm)
        if md not in modes:
            modes.append(md)
        dn.append(4 * names.index(nm))
        dm.append(6 * modes.index(md))
    o.append("DISN:  ; opcode high byte -> offset of its name in NAMEG")
    o += ["    .word " + ", ".join(str(x) for x in dn[i : i + 16]) for i in range(0, 256, 16)]
    o.append("DISM:  ; opcode high byte -> offset of its mode in MODEG")
    o += ["    .word " + ", ".join(str(x) for x in dm[i : i + 16]) for i in range(0, 256, 16)]
    o.append("NAMEG:")
    o += ["    .word " + ", ".join(str(G[c]) for c in nm) for nm in names]
    o.append("MODEG:")
    o += ["    .word " + ", ".join(str(G[c]) for c in md) for md in modes]
    return "\n".join(o) + "\n"


