"""Generate docs/isa.md from arch.py (the instruction-set reference).

usage: python3 -m quine.isadoc > docs/isa.md
CI regenerates it and fails if the committed copy differs.
"""

from __future__ import annotations

from . import arch

SEM = {
    "LDA": "A <- M; Z,N",
    "LDX": "X <- M; Z,N",
    "LDY": "Y <- M; Z,N",
    "STA": "M <- A (RAM)",
    "STX": "M <- X (RAM)",
    "STY": "M <- Y (RAM)",
    "ADD": "A <- A + M; Z,N,C",
    "ADC": "A <- A + M + C; Z,N,C",
    "SUB": "A <- A - M (C = no borrow); Z,N,C",
    "SBC": "A <- A + ~M + C; Z,N,C",
    "AND": "A <- A & M; Z,N",
    "OR": "A <- A \\| M; Z,N",
    "XOR": "A <- A ^ M; Z,N",
    "CMP": "A - M; Z,N,C",
    "CPX": "X - M; Z,N,C",
    "CPY": "Y - M; Z,N,C",
    "BRA": "branch always",
    "BEQ": "branch if Z",
    "BNE": "branch if not Z",
    "BCS": "branch if C",
    "BCC": "branch if not C",
    "BMI": "branch if N",
    "BPL": "branch if not N",
    "DBNE": "X <- X - 1; branch if X != 0 (no flags)",
    "SHL": "C <- A[15], A <- A << 1; Z,N",
    "SHR": "C <- A[0], A <- A >> 1; Z,N",
    "ROL": "A <- {A[14:0], C}, C <- A[15]; Z,N",
    "ROR": "A <- {C, A[15:1]}, C <- A[0]; Z,N",
    "SWAB": "A <- {A[7:0], A[15:8]}; Z,N",
    "TAX": "X <- A; Z,N",
    "TAY": "Y <- A; Z,N",
    "TXA": "A <- X; Z,N",
    "TYA": "A <- Y; Z,N",
    "TSX": "X <- SP; Z,N",
    "TXS": "SP <- X[7:0]",
    "INX": "X <- X + 1; Z,N",
    "INY": "Y <- Y + 1; Z,N",
    "DEX": "X <- X - 1; Z,N",
    "DEY": "Y <- Y - 1; Z,N",
    "CLC": "C <- 0",
    "SEC": "C <- 1",
    "PHA": "RAM[$0200+SP] <- A; SP <- SP - 1",
    "PLA": "SP <- SP + 1; A <- RAM[$0200+SP]; Z,N",
    "RTS": "SP <- SP + 1; PC <- RAM[$0200+SP]",
    "JMP": "PC <- operand",
    "JSR": "RAM[$0200+SP] <- return address; SP <- SP - 1; PC <- operand",
    "JMPX": "PC <- ROM[operand + X] (jump table)",
}


def main():
    o = []
    w = o.append
    w("# CPU-Quine instruction set")
    w("")
    w("<!-- GENERATED by `python3 -m quine.isadoc` from quine/arch.py; do not edit. -->")
    w("")
    w("16-bit words, word addressed.  Registers A, X, Y (16 bits), SP (8), PC (15), flags Z, N, C.")
    w("Internal: IR (16), MU (2-bit microstate).  Every flip-flop resets to zero.")
    w("")
    w("## Encoding")
    w("")
    w("| Form | Bits | Operand word |")
    w("| --- | --- | --- |")
    w("| Memory | `1 oooo mm s 00000000`: op, mode (imm, abs, abs+X, abs+Y), space (0 ROM, 1 RAM) | always |")
    w("| Other | `0 ppppp aaaaaaaaaa`: op, 10-bit signed branch offset from the next word | JMP, JSR, JMPX |")
    w("")
    w("Stores always write RAM and treat the immediate mode as absolute.  Encodings with no")
    w("instruction (op 28) execute as a 3-cycle no-op.  The opcode's high byte is the stepper's")
    w("dispatch index.")
    w("")
    w("## Memory instructions")
    w("")
    w("`M` is the operand (immediate) or the word at operand (+X or +Y) in the selected space.")
    w("")
    w("| Op | Code | Cycles (imm / abs) | Effect |")
    w("| --- | --- | --- | --- |")
    for i, op in enumerate(arch.MEM_OPS):
        imm = arch.encode_mem(op, "imm", 0) >> 8
        ab = arch.encode_mem(op, "abs", 1) >> 8
        w(f"| {op} | `{0x10 | i:05b}` | {arch.cycles(imm)} / {arch.cycles(ab)} | {SEM[op]} |")
    w("")
    w("## Other instructions")
    w("")
    w("| Op | Code | Cycles | Effect |")
    w("| --- | --- | --- | --- |")
    for i, op in enumerate(arch.OP5):
        if op is None:
            continue
        hb = arch.encode_op5(op) >> 8
        w(f"| {op} | `0{i:05b}` | {arch.cycles(hb)} | {SEM[op]} |")
    w("")
    w("## Timing")
    w("")
    w("Every instruction starts with a fetch cycle (drive PC, PC += 1) and a decode cycle")
    w("(IR <= RDATA, PC += 1 if the opcode has an operand word).  Its last cycle drives the")
    w("address of the next instruction in ROM space, so at every instruction boundary")
    w("RDATA equals ROM[PC].")
    w("")
    w("## Memory")
    w("")
    w("| Space | Addresses | Notes |")
    w("| --- | --- | --- |")
    w("| ROM | 32K words | reads use address bits [14:0]; never written |")
    w("| RAM | $0000-$7FFF | 128 pages of 256 words; cleared by the reset controller |")
    w(
        f"| I/O | ${arch.IO_DEBUG:04X}, ${arch.IO_RESET:04X} | write-only: debug port, self-reset; reads above $7FFF return 0 |"
    )
    w("")
    w("The address driven in cycle t is read at the rising edge ending cycle t and appears")
    w("on RDATA in cycle t+1.  A read happens every cycle; a write is read-first.")
    print("\n".join(o))


if __name__ == "__main__":
    main()
